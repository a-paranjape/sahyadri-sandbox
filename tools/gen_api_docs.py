#!/usr/bin/env python3
"""Generate the API reference in ``docs/api/`` from the docstrings of the repository's Python code and the header
comments of its shell and PBS scripts.

Usage (from anywhere; no imports of the documented code, it is only parsed with ``ast``)::

    python3 tools/gen_api_docs.py            # (re)write docs/api/
    python3 tools/gen_api_docs.py --check    # exit 1 if docs/api/ is out of date (e.g. before a commit)

Output: ``docs/api/README.md`` (index of all modules and scripts with their one-line summaries), one Markdown page
per Python module (``docs/api/<path>.md``: module docstring, then every class, method and top-level function with
its signature and docstring; nested helper functions are left out) and ``docs/api/scripts.md`` (the header
comment of every shell / PBS script). GitHub renders the pages directly.

Covered: all tracked ``*.py``, ``*.sh`` and ``*.pbs`` files except ``Sahyadri_pegasus/`` (an old copy of the
repository), ``old/`` directories (Python 2 code) and ``code/`` (third-party codes; their own documentation).
Docstrings use reStructuredText-style ````code```` and ``:func:`name``` roles; they are converted to Markdown
code spans. A docstring with indented lines (usage blocks, tables) is shown as preformatted text.
"""
import ast
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'api')
EXCLUDE = re.compile(r'^(Sahyadri_pegasus/|code/)|(^|/)old/')
HEADER = ('<!-- Generated by tools/gen_api_docs.py from the docstrings; do not edit by hand. '
          'Regenerate: python3 tools/gen_api_docs.py -->\n\n')


def tracked(patterns):
    """Tracked files matching ``patterns`` (git pathspecs), without the excluded trees, sorted."""
    out = subprocess.check_output(['git', '-C', ROOT, 'ls-files'] + patterns, text=True).split()
    return sorted(p for p in out if not EXCLUDE.search(p))


def md_inline(text):
    """reST inline markup -> Markdown: ``x`` and :role:`x` become `x`."""
    text = re.sub(r':(?:func|class|meth|mod|attr|data):`~?([^`]+)`', r'`\1`', text)
    text = re.sub(r'``([^`]+)``', r'`\1`', text)
    parts = text.split('`')            # outside code spans: < > & would be read as HTML, * _ as emphasis
    for i in range(0, len(parts), 2):
        parts[i] = (parts[i].replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                    .replace('*', r'\*').replace('_', r'\_'))
    return '`'.join(parts)


def md_doc(doc):
    """A docstring as Markdown: preformatted if it has indented lines, otherwise paragraphs with code spans."""
    if not doc:
        return '_No docstring._\n'
    lines = doc.strip('\n').split('\n')
    if any(l.startswith((' ', '\t')) for l in lines if l.strip()) or '::' in doc:
        return '```text\n' + doc.strip('\n') + '\n```\n'
    paras = '\n'.join(lines).split('\n\n')
    return '\n\n'.join(md_inline(p) for p in paras) + '\n'


def summary(doc):
    """First sentence (up to the first blank line) of a docstring, on one line."""
    if not doc:
        return ''
    first = doc.strip().split('\n\n')[0]
    return md_inline(' '.join(l.strip() for l in first.split('\n')))


def signature(node):
    """``name(args)`` of a function node (defaults and annotations as written)."""
    try:
        return '%s(%s)' % (node.name, ast.unparse(node.args))
    except Exception:  # noqa: BLE001
        return node.name + '(...)'


def anchor(name):
    """GitHub heading anchor of a heading text."""
    return re.sub(r'[^a-z0-9_ -]', '', name.lower()).replace(' ', '-')


def module_page(path):
    """Markdown page of one Python module and its one-line summary (for the index)."""
    src = open(os.path.join(ROOT, path), encoding='utf-8', errors='replace').read()
    try:
        tree = ast.parse(src)
    except SyntaxError as e:
        return ('# `%s`\n\nNot parsed (%s).\n' % (path, e.msg)), 'not parsed'
    rel_src = os.path.relpath(os.path.join(ROOT, path), os.path.dirname(os.path.join(OUT, path)))
    mdoc = ast.get_docstring(tree)
    out = [HEADER, '# `%s`\n\n' % path, 'Source: [%s](%s)\n\n' % (os.path.basename(path), rel_src), md_doc(mdoc), '\n']
    items = []
    for n in tree.body:
        if isinstance(n, ast.ClassDef):
            items.append(('class', n))
        elif isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
            items.append(('function', n))
    if items:
        out.append('## Contents\n\n')
        for kind, n in items:
            h = ('class %s' % n.name) if kind == 'class' else n.name
            out.append('- [`%s`](#%s) - %s\n' % (h, anchor(h), summary(ast.get_docstring(n))))
        out.append('\n')
    for kind, n in items:
        if kind == 'class':
            bases = ', '.join(ast.unparse(b) for b in n.bases)
            out.append('## class %s\n\n```python\nclass %s%s\n```\n\n' % (n.name, n.name, '(%s)' % bases if bases else ''))
            out.append(md_doc(ast.get_docstring(n)) + '\n')
            for m in n.body:
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    out.append('### %s.%s\n\n```python\n%s\n```\n\n' % (n.name, m.name, signature(m)))
                    out.append(md_doc(ast.get_docstring(m)) + '\n')
        else:
            out.append('## %s\n\n```python\n%s\n```\n\n' % (n.name, signature(n)))
            out.append(md_doc(ast.get_docstring(n)) + '\n')
    return ''.join(out), summary(mdoc)


def script_header(path):
    """Leading comment block of a shell / PBS script (after the shebang; PBS directives left out)."""
    lines = []
    for l in open(os.path.join(ROOT, path), encoding='utf-8', errors='replace'):
        if l.startswith('#!') and not lines:
            continue
        if l.startswith('#PBS') or (not l.strip() and not lines):
            continue
        if not l.startswith('#'):
            break
        lines.append(l[1:].rstrip('\n')[1:] if l[1:2] == ' ' else l[1:].rstrip('\n'))
    return '\n'.join(lines).strip('\n')


def build():
    """All generated files as {path relative to docs/api: text}."""
    files, index = {}, {}
    for p in tracked(['*.py']):
        page, summ = module_page(p)
        files[p[:-3] + '.md'] = page
        index.setdefault(os.path.dirname(p) or '.', []).append((p, summ))
    scripts = tracked(['*.sh', '*.pbs'])
    sp = [HEADER, '# Shell and PBS scripts\n\nThe header comment of every script (usage, configuration, what it writes).\n\n']
    for p in scripts:
        rel = os.path.relpath(os.path.join(ROOT, p), OUT)
        h = script_header(p)
        sp.append('## `%s`\n\nSource: [%s](%s)\n\n' % (p, os.path.basename(p), rel))
        sp.append(('```text\n%s\n```\n\n' % h) if h else '_No header comment._\n\n')
    files['scripts.md'] = ''.join(sp)
    ix = [HEADER, '# API reference\n\n',
          'Generated from the docstrings of the Python modules and the header comments of the shell and PBS '
          'scripts by [`tools/gen_api_docs.py`](../../tools/gen_api_docs.py). Guides: '
          '[pkdgrav3 pipeline on pawna](../pkdgrav3_pipeline_pawna.md), '
          '[run manager](../../tools/sahyadri_manager/README.md), '
          '[halo potential tools handover](../handover_xcorr_vprof.md).\n\n',
          '- [Shell and PBS scripts](scripts.md) (%d scripts)\n\n' % len(scripts)]
    order = ['tools/sahyadri_manager', 'tools', 'scripts/pkdgrav3_pipeline', 'scripts/pkdgrav3_pipeline/production',
             'scripts/post-process', 'scripts/gadget_pkdgrav3_compare', 'reports/gadget_pkdgrav3_potential']
    for d in sorted(index, key=lambda d: (order.index(d) if d in order else len(order), d)):
        ix.append('## %s\n\n| Module | Summary |\n|---|---|\n' % ('`%s/`' % d if d != '.' else 'top level'))
        for p, s in index[d]:
            ix.append('| [`%s`](%s) | %s |\n' % (os.path.basename(p), p[:-3] + '.md', s.replace('|', '\\|')))
        ix.append('\n')
    files['README.md'] = ''.join(ix)
    return files


def main():
    """Write ``docs/api`` (or, with ``--check``, report whether it is up to date)."""
    files = build()
    old = {}
    for dp, _ds, fs in os.walk(OUT):
        for f in fs:
            p = os.path.join(dp, f)
            old[os.path.relpath(p, OUT)] = open(p, encoding='utf-8').read()
    if '--check' in sys.argv:
        stale = sorted(set(files) ^ set(old) | {k for k in files if old.get(k) != files[k]})
        print('docs/api up to date' if not stale else 'docs/api out of date: %s' % ', '.join(stale[:10]))
        return 1 if stale else 0
    for rel in set(old) - set(files):
        os.unlink(os.path.join(OUT, rel))
    for rel, text in files.items():
        p = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        if old.get(rel) != text:
            with open(p, 'w', encoding='utf-8') as f:
                f.write(text)
    print('docs/api: %d files (%d changed)' % (len(files), sum(old.get(k) != v for k, v in files.items())))
    return 0


if __name__ == '__main__':
    sys.exit(main())
